    // THÈME — Application immédiate (avant rendu DOM pour éviter le flash)
    // ══════════════════════════════════════════════════════════════════════════

    function applyTheme(theme) {
        if (theme === 'dark') {
            document.documentElement.setAttribute('data-theme', 'dark');
        } else {
            document.documentElement.setAttribute('data-theme', 'light');
        }
        try { localStorage.setItem('sf_theme', theme); } catch (e) {}
    }

    // Application immédiate au chargement du script (avant DOMContentLoaded)
    (function initTheme() {
        let saved = 'light';
        try { saved = localStorage.getItem('sf_theme') || 'light'; } catch (e) {}
        applyTheme(saved);
    })();

    // ══════════════════════════════════════════════════════════════════════════
    // LANGUE — Application des traductions
    // ══════════════════════════════════════════════════════════════════════════

    function applyLanguage(lang) {
        const t = TRANSLATIONS[lang] || TRANSLATIONS['fr'];

        // Direction du texte (RTL pour l'arabe)
        document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
        document.documentElement.setAttribute('lang', lang);

        // Traduit tous les éléments avec data-i18n
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (t[key] !== undefined) {
                // Pour les inputs placeholder
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    el.placeholder = t[key];
                } else {
                    el.textContent = t[key];
                }
            }
        });

        // Traduit les placeholders marqués data-i18n-placeholder
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (t[key] !== undefined) el.placeholder = t[key];
        });

        try { localStorage.setItem('sf_lang', lang); } catch (e) {}
    }

    // Application immédiate au chargement du script
    (function initLang() {
        let saved = 'fr';
        try { saved = localStorage.getItem('sf_lang') || 'fr'; } catch (e) {}
        // On applique la langue après DOMContentLoaded
        if (document.readyState === 'loading') {
            document.addEventListener('DOMContentLoaded', () => applyLanguage(saved));
        } else {
            applyLanguage(saved);
        }
    })();

    // ══════════════════════════════════════════════════════════════════════════
    // API PUBLIQUE
    // ══════════════════════════════════════════════════════════════════════════
    return {
        applyTheme,
        applyLanguage,
        TRANSLATIONS,
        getCurrentLang: () => {
            try { return localStorage.getItem('sf_lang') || 'fr'; } catch (e) { return 'fr'; }
        },
        getCurrentTheme: () => {
            try { return localStorage.getItem('sf_theme') || 'light'; } catch (e) { return 'light'; }
        }
    };

